<?php
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
// Generates application/config/tenancy_tables.php (table scopes for the tenant-aware DB driver)
// from the migration manifest.
// Usage: php tools/tenancy/gen_tenancy_tables.php tools/tenancy/manifest.json application/config/tenancy_tables.php

[$_, $manifestFile, $outFile] = $argv;
$manifest = json_decode(file_get_contents($manifestFile), true);
$groups = ['tenant' => [], 'hybrid' => [], 'platform' => []];
foreach ($manifest as $m) $groups[$m['scope']][] = strtolower($m['table']);
foreach ($groups as &$g) sort($g, SORT_STRING);
unset($g);

$list = function (array $tables) {
    return "array(\n" . implode('', array_map(function ($t) { return "    '$t',\n"; }, $tables)) . ")";
};
$php = "<?php\n\ndefined('BASEPATH') or exit('No direct script access allowed');\n\n"
    . "/*\n| Generated by tools/tenancy/gen_tenancy_tables.php from the migration manifest. Do not edit.\n"
    . "|\n| tenancy_tenant_tables   every row belongs to one school: reads, updates and deletes are\n"
    . "|                         filtered by school_id; inserts get school_id set.\n"
    . "| tenancy_hybrid_tables   school_id NULL = system row shared by all schools: reads see system\n"
    . "|                         rows plus the school's own; writes only touch the school's own rows.\n"
    . "| tenancy_platform_tables shared by all schools, never filtered.\n"
    . "| Names are lowercase.\n*/\n\n"
    . "\$config['tenancy_tenant_tables'] = " . $list($groups['tenant']) . ";\n\n"
    . "\$config['tenancy_hybrid_tables'] = " . $list($groups['hybrid']) . ";\n\n"
    . "\$config['tenancy_platform_tables'] = " . $list($groups['platform']) . ";\n";
file_put_contents($outFile, $php);
echo 'tenant=' . count($groups['tenant']) . ' hybrid=' . count($groups['hybrid']) . ' platform=' . count($groups['platform']) . "\n";
