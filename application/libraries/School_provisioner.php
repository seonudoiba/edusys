<?php

defined('BASEPATH') or exit('No direct script access allowed');

require_once APPPATH . 'libraries/Tenant.php';
require_once APPPATH . 'libraries/Tenant_resolver.php';
require_once APPPATH . 'libraries/Seeder.php';

/**
 * Sets up a school in the shared database: the only provisioning path.
 *
 * A school is rows, not an instance: no folder, no database, no config file.
 * provision() runs in one transaction, so a school is either fully set up or not at all:
 *
 *   1. checks the registry row: not the platform school, valid and free subdomain, email set,
 *      not set up already;
 *   2. loads the default data (application/seeds/default, generated by
 *      tools/tenancy/gen_default_seed.php) under new ids, remapping references between those tables;
 *   3. fills the school's settings row (name, email, phone, address, a new cron key);
 *   4. creates the super admin (role 7) with an unusable random password and a one-time
 *      set-password code;
 *   5. marks the school enabled and set up (status = 1, cron_flag = 1).
 *
 * Runs on the platform host (or the CLI). The returned set-password link opens on the
 * school's own subdomain (site/admin_resetpassword/<code>).
 */
class School_provisioner
{
    const SUPER_ADMIN_ROLE = 7;

    /** @var CI_Controller */
    private $CI;

    public function __construct()
    {
        $this->CI = &get_instance();
        $this->CI->load->database();
        $this->CI->config->load('tenancy');
    }

    /**
     * @param int $school_id registry id
     * @return array ['school_id', 'subdomain', 'admin_email', 'set_password_url']
     * @throws RuntimeException with a message suitable for the platform admin
     */
    public function provision($school_id)
    {
        if (!is_cli() && !Tenant::is_platform()) {
            throw new RuntimeException('Schools can only be set up from the platform.');
        }
        $db = $this->CI->db;
        $school = $db->where('id', (int) $school_id)->get('school')->row_array();
        $this->validate($school);

        $code = bin2hex(random_bytes(20));
        $debug = $db->db_debug;
        $db->db_debug = false; // errors become exceptions below instead of an error page mid-transaction
        $db->trans_begin();
        try {
            $db->without_tenant(function ($db) use ($school, $code) {
                $map = $this->load_default_data($db, (int) $school['id'], !empty($school['is_platform']));
                $this->fill_settings($db, $school);
                $this->create_super_admin($db, $school, $code);
                $db->where('id', (int) $school['id'])->update('school', array('status' => 1, 'cron_flag' => 1));
                return $map;
            });
            if ($db->trans_status() === false) {
                $error = $db->error();
                throw new RuntimeException('Database error: ' . $error['message']);
            }
            $db->trans_commit();
        } catch (Throwable $e) {
            $db->trans_rollback();
            $db->db_debug = $debug;
            throw new RuntimeException('Setting up the school failed and was rolled back: ' . $e->getMessage(), 0, $e);
        }
        $db->db_debug = $debug;

        return array(
            'school_id' => (int) $school['id'],
            'subdomain' => $school['subdomain'],
            'admin_email' => $school['email_address'],
            'set_password_url' => $this->url_for($school) . 'site/admin_resetpassword/' . $code,
        );
    }

    /** Throws when the school can't be set up; returns silently otherwise. */
    public function validate($school)
    {
        if (empty($school)) {
            throw new RuntimeException('School not found.');
        }
        if (!empty($school['is_platform'])) {
            // The platform school (central host, no subdomain) is set up once, at installation, from the CLI.
            if (!is_cli()) {
                throw new RuntimeException('The platform school is set up from the command line (php index.php school_setup run <id>).');
            }
        } else {
            $error = $this->subdomain_error(isset($school['subdomain']) ? (string) $school['subdomain'] : '', (int) $school['id']);
            if ($error !== null) {
                throw new RuntimeException($error);
            }
        }
        if (empty($school['email_address']) || !filter_var($school['email_address'], FILTER_VALIDATE_EMAIL)) {
            throw new RuntimeException('The school needs a valid email address: the super admin account uses it.');
        }
        $db = $this->CI->db;
        $set_up = $db->without_tenant(function ($db) use ($school) {
            return $db->where('school_id', (int) $school['id'])->count_all_results('sch_settings') > 0;
        });
        if ($set_up) {
            throw new RuntimeException('This school is already set up.');
        }
    }

    /**
     * Why a subdomain can't be used, or null when it can.
     *
     * @param string $subdomain
     * @param int|null $school_id the school it is for (it may keep its own subdomain)
     * @return string|null
     */
    public function subdomain_error($subdomain, $school_id = null)
    {
        if ($subdomain === '') {
            return 'Set a subdomain for the school first.';
        }
        if (!Tenant_resolver::is_valid_label($subdomain) || $subdomain !== strtolower($subdomain)) {
            return 'The subdomain may use lowercase letters, digits and inner hyphens (1-63 characters).';
        }
        if (in_array($subdomain, (array) $this->CI->config->item('tenancy_reserved_subdomains'), true)) {
            return "'$subdomain' is reserved.";
        }
        $db = $this->CI->db;
        $db->where('subdomain', $subdomain);
        if ($school_id) {
            $db->where('id !=', (int) $school_id);
        }
        if ($db->count_all_results('school') > 0) {
            return "The subdomain '$subdomain' is already used by another school.";
        }
        return null;
    }

    /** Where a school is served: its subdomain, or the first central host for the platform school. */
    public function url_for(array $school)
    {
        if (!empty($school['is_platform'])) {
            $hosts = (array) $this->CI->config->item('tenancy_central_hosts');
            $https = is_https() || $this->CI->config->item('tenancy_force_https');
            return ($https ? 'https' : 'http') . '://' . (isset($hosts[0]) ? $hosts[0] : 'localhost') . '/';
        }
        return $this->school_url($school['subdomain']);
    }

    /** https://<subdomain>.<base domain>/ */
    public function school_url($subdomain)
    {
        $https = is_https() || $this->CI->config->item('tenancy_force_https');
        return ($https ? 'https' : 'http') . '://' . $subdomain . '.' . $this->CI->config->item('tenancy_base_domain') . '/';
    }

    /**
     * Inserts the default rows for a school under new ids. Rows tagged `$platform_only` (the school
     * registry, plans and subscriptions modules) are loaded for the platform school only; rows that
     * point at a skipped row are skipped too.
     *
     * @return array table => [template id => new id]
     */
    private function load_default_data($db, $school_id, $is_platform = false)
    {
        $skipped = array();
        $files = glob(APPPATH . 'seeds/default/[0-9][0-9][0-9]_*.php');
        if (!$files) {
            throw new RuntimeException('The default seed (application/seeds/default) is missing.');
        }
        sort($files, SORT_STRING);
        $map = array();
        foreach ($files as $file) {
            require_once $file;
            $class = 'Seed_default_' . preg_replace('/^\d{3}_/', '', basename($file, '.php'));
            $seed = new $class();
            $table = $seed->table;
            $refs = isset($seed->references) ? $seed->references : array();
            $map[$table] = array();
            $self_refs = array();
            $platform_only = isset($seed->platform_only) ? array_flip($seed->platform_only) : array();
            foreach ($seed->rows() as $row) {
                $assoc = array_combine($seed->columns, $row);
                $template_id = $assoc['id'];
                $skip = !$is_platform && isset($platform_only[$template_id]);
                foreach ($refs as $col => $ref_table) {
                    $skip = $skip || ($assoc[$col] !== null && isset($skipped[$ref_table][$assoc[$col]]));
                }
                if ($skip) {
                    $skipped[$table][$template_id] = true;
                    continue;
                }
                unset($assoc['id']);
                foreach ($refs as $col => $ref_table) {
                    $value = $assoc[$col];
                    if ($value === null || $value === '' || (string) $value === '0') {
                        continue;
                    }
                    if ($ref_table === $table) {
                        $self_refs[$template_id][$col] = $value; // resolved once the whole table is in
                        $assoc[$col] = null;
                        continue;
                    }
                    if (!isset($map[$ref_table][$value])) {
                        throw new RuntimeException("Default data: $table.$col refers to missing $ref_table row $value.");
                    }
                    $assoc[$col] = $map[$ref_table][$value];
                }
                $assoc['school_id'] = $school_id;
                if ($self_refs && isset($self_refs[$template_id])) {
                    foreach ($self_refs[$template_id] as $col => $_) {
                        $assoc[$col] = isset($assoc[$col]) ? $assoc[$col] : 0; // NOT NULL self references start at 0
                    }
                }
                $this->insert_or_fail($db, $table, $assoc);
                $map[$table][$template_id] = (int) $db->insert_id();
            }
            foreach ($self_refs as $template_id => $cols) {
                $update = array();
                foreach ($cols as $col => $value) {
                    $update[$col] = isset($map[$table][$value]) ? $map[$table][$value] : 0;
                }
                $db->where('id', $map[$table][$template_id])->update($table, $update);
            }
        }
        return $map;
    }

    private function fill_settings($db, array $school)
    {
        $db->where('school_id', (int) $school['id'])->update('sch_settings', array(
            'name' => $school['school_name'],
            'email' => $school['email_address'],
            'phone' => (string) $school['phone_number'],
            'address' => (string) $school['school_address'],
            'cron_secret_key' => bin2hex(random_bytes(16)),
            'base_url' => '',
            'folder_path' => '',
        ));
    }

    private function create_super_admin($db, array $school, $code)
    {
        $settings = $db->select('lang_id')->where('school_id', (int) $school['id'])->get('sch_settings')->row();
        $name = trim((string) $school['owner_name']) !== '' ? trim((string) $school['owner_name']) : 'Super Admin';
        $staff = $this->required_defaults($db, 'staff');
        $staff = array_merge($staff, array(
            'school_id' => (int) $school['id'],
            'employee_id' => 'ADMIN',
            'lang_id' => $settings ? (int) $settings->lang_id : 0,
            'name' => $name,
            'email' => $school['email_address'],
            'contact_no' => (string) $school['phone_number'],
            // Unusable until the owner sets a password through the one-time link.
            'password' => password_hash(bin2hex(random_bytes(24)), PASSWORD_DEFAULT),
            'verification_code' => $code,
            'is_active' => 1,
            'date_of_joining' => date('Y-m-d'),
        ));
        $this->insert_or_fail($db, 'staff', $staff);
        $staff_id = (int) $db->insert_id();
        $role = array_merge($this->required_defaults($db, 'staff_roles'), array(
            'school_id' => (int) $school['id'],
            'role_id' => self::SUPER_ADMIN_ROLE,
            'staff_id' => $staff_id,
        ));
        $this->insert_or_fail($db, 'staff_roles', $role);
    }

    private function insert_or_fail($db, $table, array $row)
    {
        if (!$db->insert($table, $row)) {
            $error = $db->error();
            throw new RuntimeException("Inserting into $table failed: " . $error['message']);
        }
    }

    /** Empty values for NOT NULL columns without a default (the legacy schema has many). */
    private function required_defaults($db, $table)
    {
        $columns = $db->query(
            'SELECT column_name AS name, data_type AS type FROM information_schema.columns '
            . 'WHERE table_schema = DATABASE() AND table_name = ? AND is_nullable = ? AND column_default IS NULL AND extra NOT LIKE ?',
            array($table, 'NO', '%auto_increment%')
        )->result();
        $values = array();
        foreach ($columns as $c) {
            $type = strtolower($c->type);
            if (in_array($type, array('date', 'datetime', 'timestamp'), true)) {
                $values[$c->name] = $type === 'date' ? date('Y-m-d') : date('Y-m-d H:i:s');
            } elseif (preg_match('/int|decimal|float|double/', $type)) {
                $values[$c->name] = 0;
            } else {
                $values[$c->name] = '';
            }
        }
        unset($values['school_id']);
        return $values;
    }
}
