<?php

defined('BASEPATH') or exit('No direct script access allowed');

/**
 * CLI seed runner.
 *
 *   php index.php seed run platform    # school registry, plans, languages, system roles
 *   php index.php seed run school_1    # school 1 data (from the central smartschool database)
 *   php index.php seed run school_2    # school 2 data (from school_182)
 *   php index.php seed run all         # platform, then every school_<id> group
 *   php index.php seed status          # list groups and file counts
 *
 * Seed files live in application/seeds/<group>/NNN_<table>.php, one table per file.
 * A school group's id comes from its folder name (school_<id>).
 */
class Seed extends CI_Controller
{
    private $path;

    public function __construct()
    {
        parent::__construct();
        if (!is_cli()) {
            show_404();
        }
        $this->path = APPPATH . 'seeds/';
        require_once APPPATH . 'libraries/Seeder.php';
        $this->load->database();
    }

    public function status()
    {
        foreach ($this->groups() as $group) {
            echo str_pad($group, 12) . count($this->files($group)) . " seed files\n";
        }
    }

    public function run($group = null)
    {
        if ($group === null) {
            $this->fail('Usage: php index.php seed run <platform|school_<id>|all>');
        }
        $groups = $group === 'all' ? $this->groups() : [$group];
        foreach ($groups as $g) {
            if (!in_array($g, $this->groups(), true)) {
                $this->fail("Unknown seed group '$g'. Available: " . implode(', ', $this->groups()));
            }
        }
        foreach ($groups as $g) {
            $this->run_group($g);
        }
    }

    /**
     * The platform's public website content (application/seeds/platform_content, generated by
     * tools/tenancy/gen_platform_content.php): identity, logos, pages and menus. Each version is applied
     * once per server, so running it again changes nothing and admin edits survive until a new version is
     * shipped on purpose. A new version replaces the About, Laboratory and Contact pages and both menus;
     * other pages are only added when missing.
     */
    public function content()
    {
        $file = $this->path . 'platform_content/content.json';
        $data = is_file($file) ? json_decode(file_get_contents($file), true) : null;
        if (!$data) {
            $this->fail('application/seeds/platform_content/content.json is missing or unreadable.');
        }
        $db = $this->db;
        $school = $db->where('is_platform', 1)->get('school')->row();
        if (!$school) {
            $this->fail('No platform school yet: set it up first (php index.php school_setup run <id>).');
        }
        $sid = (int) $school->id;
        $marker = 'content_seed_version';
        $applied = $db->where('name', $marker)->get('platform_settings')->row();
        if ($applied && (int) $applied->value >= (int) $data['version']) {
            echo "Platform content was already applied on this server: nothing changed.\n";
            return;
        }
        $db->trans_begin();
        try {
            $db->without_tenant(function ($db) use ($data, $sid, $marker) {
                $ids = array();
                foreach ($data['pages'] as $p) {
                    $row = $db->select('id')->where(array('school_id' => $sid, 'slug' => $p['slug']))->get('front_cms_pages')->row();
                    if ($row) {
                        if (in_array($p['slug'], array('contact-us', 'about-us', 'edusys-solar-computer-lab'), true)) {
                            $db->where('id', (int) $row->id)->update('front_cms_pages', array('title' => $p['title'], 'description' => $p['description']));
                            echo "  page updated: {$p['slug']}\n";
                        }
                        $ids[$p['slug']] = (int) $row->id;
                        continue;
                    }
                    $db->insert('front_cms_pages', $p + array('school_id' => $sid, 'page_type' => 'manual', 'is_homepage' => 0,
                        'feature_image' => '', 'publish' => 0, 'is_active' => 'yes'));
                    $ids[$p['slug']] = (int) $db->insert_id();
                    echo "  page added:   {$p['slug']}\n";
                }
                $home = $db->select('id')->where(array('school_id' => $sid, 'is_homepage' => 1))->get('front_cms_pages')->row();
                $ids['home'] = $home ? (int) $home->id : 0;

                foreach ($data['menus'] as $menu_slug => $items) {
                    $menu = $db->select('id')->where(array('school_id' => $sid, 'slug' => $menu_slug))->get('front_cms_menus')->row();
                    if (!$menu) {
                        throw new RuntimeException("Menu $menu_slug not found.");
                    }
                    $db->where(array('school_id' => $sid, 'menu_id' => (int) $menu->id))->delete('front_cms_menu_items');
                    foreach ($items as $i => $item) {
                        $values = array(
                            'weight' => $i + 1,
                            'page_id' => isset($item['page']) ? $ids[$item['page']] : 0,
                            'ext_url' => isset($item['link']) ? 1 : null,
                            'ext_url_link' => isset($item['link']) ? $item['link'] : null,
                            'publish' => 0,
                        );
                        $db->insert('front_cms_menu_items', $values + array('school_id' => $sid, 'menu_id' => (int) $menu->id, 'menu' => $item['menu'],
                            'parent_id' => 0, 'slug' => $item['slug']));
                        echo "  menu {$menu_slug}: {$item['menu']}\n";
                    }
                }
                // The slider, unless this server already has one.
                $program = $db->select('id')->where(array('school_id' => $sid, 'type' => 'banner'))->get('front_cms_programs')->row();
                if (!$program) {
                    $db->insert('front_cms_programs', array('school_id' => $sid, 'type' => 'banner', 'title' => 'Banner Images'));
                    $program_id = (int) $db->insert_id();
                } else {
                    $program_id = (int) $program->id;
                }
                if ($db->where('program_id', $program_id)->count_all_results('front_cms_program_photos') === 0) {
                    foreach (!empty($data['banners']) ? $data['banners'] : array() as $banner) {
                        $db->insert('front_cms_media_gallery', $banner + array('school_id' => $sid));
                        $db->insert('front_cms_program_photos', array('school_id' => $sid, 'program_id' => $program_id, 'media_gallery_id' => (int) $db->insert_id()));
                        echo "  slider image: {$banner['image']}\n";
                    }
                }
                $db->where('school_id', $sid)->update('sch_settings', $data['identity']);
                $db->where('school_id', $sid)->update('front_cms_settings', $data['front']);
                $db->where('name', $marker)->delete('platform_settings');
                $db->insert('platform_settings', array('name' => $marker, 'value' => (string) $data['version']));
            });
            if ($db->trans_status() === false) {
                throw new RuntimeException('Database error: ' . $db->error()['message']);
            }
            $db->trans_commit();
        } catch (Throwable $e) {
            $db->trans_rollback();
            $this->fail('Nothing changed: ' . $e->getMessage());
        }
        foreach ($data['files'] as $name => $relative) {
            $target = FCPATH . 'uploads/s' . $sid . '/' . $relative;
            if (!is_dir(dirname($target))) {
                mkdir(dirname($target), 0775, true);
            }
            if (!copy($this->path . 'platform_content/files/' . $name, $target)) {
                $this->fail("Could not copy $name to $target");
            }
            @chmod($target, 0664);
        }
        echo 'Done: ' . count($data['pages']) . ' pages, ' . count($data['files']) . " files.\n";
    }

    private function run_group($group)
    {
        $school_id = null;
        if ($group !== 'platform') {
            $school_id = (int) substr($group, strlen('school_'));
            if ($this->db->where('id', $school_id)->count_all_results('school') === 0) {
                $this->fail("School $school_id is not in the registry. Run the platform seed first.");
            }
        }
        $seeds = array_map([$this, 'load_seed'], $this->files($group));

        echo "Seeding $group (" . count($seeds) . " tables)\n";
        $this->db->trans_begin();
        try {
            foreach (array_reverse($seeds) as $seed) {
                $seed->clear($this->db, $school_id);
            }
            $total = 0;
            foreach ($seeds as $seed) {
                $n = $seed->insert($this->db, $school_id);
                $total += $n;
                echo '  ' . str_pad($seed->table, 44) . $n . "\n";
            }
            if ($this->db->trans_status() === false) {
                throw new RuntimeException('Transaction failed.');
            }
            // School seeds carry plain passwords from older data.
            $this->db->without_tenant(function ($db) {
                $rows = $db->select('id, password')->where('password IS NOT NULL', null, false)->where('password <>', '')
                    ->where("password NOT LIKE '\$2y\$%'", null, false)->get('users')->result_array();
                foreach ($rows as $row) {
                    $db->where('id', (int) $row['id'])->update('users', array('password' => password_hash($row['password'], PASSWORD_DEFAULT), 'must_change_password' => 1));
                }
            });
            $this->db->trans_commit();
            echo "Done: $total rows.\n";
        } catch (Throwable $e) {
            $this->db->trans_rollback();
            $this->fail("Rolled back $group: " . $e->getMessage());
        }
    }

    private function load_seed($file)
    {
        require_once $file;
        $group = basename(dirname($file));
        $table = preg_replace('/^\d{3}_/', '', basename($file, '.php'));
        $class = 'Seed_' . $group . '_' . $table;
        if (!class_exists($class, false)) {
            $this->fail("Seed class $class not found in $file");
        }
        return new $class();
    }

    private function groups()
    {
        $groups = [];
        foreach (glob($this->path . '*', GLOB_ONLYDIR) as $dir) {
            $name = basename($dir);
            if ($name === 'platform' || preg_match('/^school_[1-9]\d*$/', $name)) {
                $groups[] = $name;
            }
        }
        usort($groups, function ($a, $b) {
            if ($a === 'platform') return -1;
            if ($b === 'platform') return 1;
            return (int) substr($a, 7) - (int) substr($b, 7);
        });
        return $groups;
    }

    private function files($group)
    {
        $files = glob($this->path . $group . '/[0-9][0-9][0-9]_*.php');
        sort($files, SORT_STRING);
        return $files;
    }

    private function fail($message)
    {
        fwrite(STDERR, $message . PHP_EOL);
        exit(1);
    }
}
